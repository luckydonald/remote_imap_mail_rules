"""The slice of the `aioimaplib` client the project uses, so tests can substitute a fake."""

from datetime import datetime
from typing import Protocol

from aioimaplib import Response


class ImapConnection(Protocol):
    """Matches `aioimaplib.IMAP4` / `IMAP4_SSL`. Writes go through `select`, `append` and `uid` (`STORE`, `COPY`, `MOVE`, `EXPUNGE`) and only `ImapClient` issues them."""

    protocol: "ProtocolState"

    async def wait_hello_from_server(self) -> None: ...
    async def login(self, user: str, password: str) -> Response: ...
    async def logout(self) -> Response: ...
    async def examine(self, mailbox: str = "INBOX") -> Response: ...
    async def select(self, mailbox: str = "INBOX") -> Response: ...
    async def status(self, mailbox: str, names: str) -> Response: ...
    async def list(self, reference_name: str, mailbox_pattern: str) -> Response: ...
    async def uid_search(self, *criteria: str, charset: str | None = "utf-8") -> Response: ...
    async def uid(self, command: str, *criteria: str) -> Response: ...
    async def append(self, message_bytes: bytes, mailbox: str = "INBOX", flags: str | None = None, date: datetime | None = None, timeout: float | None = None) -> Response: ...
    async def noop(self) -> Response: ...
    async def idle_start(self, timeout: float = ...) -> object: ...
    async def wait_server_push(self, timeout: float = ...) -> Response: ...
    def idle_done(self) -> None: ...
    def has_pending_idle(self) -> bool: ...
# end class


class ProtocolState(Protocol):
    capabilities: set[str]
    state: str
# end class
